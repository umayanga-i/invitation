import path from 'node:path';
import { expect, test } from '@playwright/test';
import { loginAsDemo } from './helpers';
import type { Invitation } from '@/lib/mock-data';

test.use({ actionTimeout: 15_000 });

// This journey owns its invitation and cleans it up, leaving existing invitations alone.
test('golden wedding details and all eight photo spaces save, reload and appear to guests', async ({ page, browser }, testInfo) => {
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  await loginAsDemo(page);
  await page.goto('/templates/wedding-golden');
  await expect(page.getByLabel('Host name(s)')).toHaveValue('Nimesh & Dilhani');
  await expect(page.getByLabel('Date', { exact: true })).toHaveValue('2026-12-27');
  await expect(page.getByLabel('RSVP deadline (optional)')).toHaveValue('2026-08-10');
  await expect(page.getByLabel('First partner’s parents')).toHaveValue('Mr. & Mrs. Sunil Perera');
  await expect(page.getByLabel('Event 1 time')).toHaveValue('09:00');
  await expect(page.getByLabel('Event 3 time')).toHaveValue('18:30');
  await expect(page.getByLabel('Event 4 time')).toHaveValue('21:00');
  const preview = page.getByLabel('Live invitation preview');
  await expect(preview.getByRole('button', { name: /^Add .*photo/ })).toHaveCount(8);
  const couple = path.resolve('public/images/templates/wedding-ivory/couple-hero.webp');
  const story = path.resolve('public/images/templates/wedding-ivory/story.webp');
  const picker = page.waitForEvent('filechooser');
  await preview.getByRole('button', { name: 'Add couple photo', exact: true }).click();
  await (await picker).setFiles(couple);
  await expect(preview.getByRole('button', { name: 'Replace couple photo' })).toBeVisible();
  await preview.getByLabel('Choose story photo').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('not an image') });
  await expect(preview.getByRole('alert')).toContainText('Choose a JPG, PNG, or WebP image.');
  await preview.getByLabel('Choose story photo').setInputFiles({ name: 'bad.png', mimeType: 'image/png', buffer: Buffer.from('not an image') });
  await expect(preview.getByRole('alert')).toContainText('This image could not be opened.');
  await preview.getByLabel('Choose story photo').setInputFiles(story);
  await expect(preview.getByRole('button', { name: 'Replace story photo' })).toBeVisible();
  for (let index = 1; index <= 6; index++) {
    await preview.getByLabel(`Choose gallery photo ${index}`, { exact: true }).setInputFiles(index % 2 ? couple : story);
    await expect(preview.getByRole('button', { name: `Replace gallery photo ${index}`, exact: true })).toBeVisible();
  }
  const previousStory = await preview.getByRole('img', { name: 'Story photo', exact: true }).getAttribute('src');
  await preview.getByLabel('Choose gallery photo 1', { exact: true }).setInputFiles(story);
  await expect(preview.getByRole('img', { name: 'Gallery photo 1', exact: true })).toHaveAttribute('src', previousStory!);
  await expect(preview.getByRole('img', { name: 'Story photo', exact: true })).toHaveAttribute('src', previousStory!);
  await page.getByLabel('Host name(s)').fill('Anu & Ravi');
  await page.getByLabel('Event title', { exact: true }).fill('Golden Photo Test');
  await page.getByLabel('Date', { exact: true }).fill('2029-12-27');
  await page.getByLabel('Time', { exact: true }).fill('11:45');
  await page.getByLabel('RSVP deadline (optional)').fill('2029-12-10');
  await page.getByLabel('Venue', { exact: true }).fill('Garden Hall');
  await page.getByLabel('First partner’s parents').fill('The Perera Family');
  await page.getByLabel('Second partner’s parents').fill('The Silva Family');
  await page.getByLabel('Story heading').fill('A new adventure');
  await page.getByLabel('Our story').fill('Our own story, saved with our photos. සිංහල தமிழ்');
  await page.getByLabel('Venue address').fill('Galle, Sri Lanka');
  await page.getByLabel('Event 1 venue').fill('Family Home');
  await page.getByLabel('Event 3 time').fill('19:00');
  await page.getByLabel('Event 4 title').fill('Dancing Together');
  await expect(preview.locator('[data-section="events"]')).toContainText('11:45 AM');
  await expect(preview.locator('[data-section="events"]')).toContainText('7:00 PM');
  const dimensions = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: innerWidth }));
  expect(dimensions.width).toBeLessThanOrEqual(dimensions.viewport);
  const creation = page.waitForResponse((response) => response.url().endsWith('/api/invitations') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save invitation', exact: true }).click();
  const response = await creation;
  expect(response.status()).toBe(201);
  const invitation = await response.json() as Invitation;
  const guestContext = await browser.newContext({ viewport: testInfo.project.use.viewport, reducedMotion: 'reduce' });
  const guestPage = await guestContext.newPage();
  guestPage.on('pageerror', (error) => errors.push(error.message));
  guestPage.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  try {
    expect(Object.keys(invitation.customData.photos!)).toHaveLength(8);
    for (const photo of Object.values(invitation.customData.photos!)) expect(photo!.length).toBeLessThanOrEqual(600_000);
    expect(invitation.customData.weddingDetails?.events[1]).toMatchObject({ time: '11:45', venue: 'Garden Hall' });
    expect((await page.request.patch(`/api/invitations/${invitation.id}`, { data: { customData: { ...invitation.customData, photos: { invalidSlot: 'data:image/png;base64,AAAA' } } } })).status()).toBe(400);
    expect((await page.request.patch(`/api/invitations/${invitation.id}`, { data: { customData: { ...invitation.customData, weddingDetails: { ...invitation.customData.weddingDetails, events: [] } } } })).status()).toBe(400);
    expect((await page.request.patch(`/api/invitations/${invitation.id}`, { data: { status: 'published' } })).ok()).toBeTruthy();
    await page.waitForURL(`**/invitations/${invitation.id}`);
    await page.goto(`/invitations/${invitation.id}/edit`);
    await expect(page.getByLabel('First partner’s parents')).toHaveValue('The Perera Family');
    await expect(page.getByLabel('Live invitation preview').getByRole('button', { name: /^Replace .*photo/ })).toHaveCount(8);
    await guestPage.goto(`/i/${invitation.slug}`);
    await expect(guestPage.locator('[data-section="hero"]')).toContainText('The Perera Family');
    await expect(guestPage.locator('[data-section="story"]')).toContainText('A new adventure');
    await expect(guestPage.locator('[data-section="story"]')).toContainText('Our own story, saved with our photos. සිංහල தமிழ்');
    await expect(guestPage.getByRole('button', { name: /(?:Add|Replace|Remove).*photo/ })).toHaveCount(0);
    await expect(guestPage.locator('input[type="file"]')).toHaveCount(0);
    await expect(guestPage.locator('[data-section="gallery"] img')).toHaveCount(6);
    await expect(guestPage.getByRole('link', { name: 'Add to Calendar' })).toHaveAttribute('href', /20291227T061500Z/);
    await expect(guestPage.getByRole('link', { name: 'Open in Maps' })).toHaveAttribute('href', /Garden%20Hall.*Galle/);
    await guestPage.getByRole('img', { name: 'Story photo', exact: true }).scrollIntoViewIfNeeded();
    await expect.poll(() => guestPage.getByRole('img', { name: 'Story photo', exact: true }).evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
    await guestPage.getByRole('img', { name: 'Gallery photo 6', exact: true }).scrollIntoViewIfNeeded();
    await expect.poll(() => guestPage.getByRole('img', { name: 'Gallery photo 6', exact: true }).evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
    expect(await guestPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    await guestPage.screenshot({ path: testInfo.outputPath('golden-invitation.png'), fullPage: true });
    await guestPage.getByLabel('Your name', { exact: true }).fill('Golden Template Guest');
    await guestPage.getByRole('button', { name: 'Send RSVP', exact: true }).click();
    await expect(guestPage.getByRole('status')).toContainText('Your response is saved');
    const savedGuests = await (await page.request.get(`/api/invitations/${invitation.id}/guests`)).json() as Array<{ name: string }>;
    expect(savedGuests.some((guest) => guest.name === 'Golden Template Guest')).toBeTruthy();
    await page.getByLabel('Live invitation preview').getByRole('button', { name: 'Remove story photo', exact: true }).click();
    await page.getByLabel('Live invitation preview').getByRole('button', { name: 'Remove gallery photo 6', exact: true }).click();
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.waitForURL(`**/invitations/${invitation.id}`);
    const updated = await (await page.request.get(`/api/invitations/${invitation.id}`)).json() as Invitation;
    expect(updated.customData.photos?.story).toBeUndefined();
    expect(updated.customData.photos?.gallery6).toBeUndefined();
    expect(updated.customData.photos?.hero).toBe(invitation.customData.photos?.hero);
    await guestPage.reload();
    await expect(guestPage.locator('[data-section="gallery"] img')).toHaveCount(5);
    await expect(guestPage.getByRole('button', { name: /(?:Add|Replace|Remove).*photo/ })).toHaveCount(0);
    expect(errors).toEqual([]);
  } finally {
    await guestContext.close();
    await page.request.delete(`/api/invitations/${invitation.id}`);
  }
});
